def main() -> int:
    existing = {}
    if OUT.exists():
        try:
            for s in json.loads(OUT.read_text(encoding="utf-8")):
                key = (s.get("artist"), s.get("title"), s.get("year"))
                existing[key] = s
        except Exception:
            existing = {}

    out = []
    for sid, artist, title, year, region in SONGS:
        rec = {
            "id": sid,
            "artist": artist,
            "title": title,
            "year": year,
            "region": region,
        }
        # Preserve verification data when the (artist, title, year) hasn't changed.
        prior = existing.get((artist, title, year))
        if prior and prior.get("verified"):
            for k in ("youtube_id", "duration", "yt_title", "yt_uploader",
                      "verified", "verified_at", "search_query"):
                if k in prior:
                    rec[k] = prior[k]
        out.append(rec)

    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    from collections import Counter
    c = Counter(s["region"] for s in out)
    total = len(out)
    print(f"Wrote {total} songs to {OUT}")
    for r, n in sorted(c.items(), key=lambda kv: -kv[1]):
        print(f"  {r:8s} {n:4d}  ({100*n/total:.1f}%)")
    ru = c.get("ussr", 0) + c.get("russia", 0)
    print(f"  russian-combined {ru} ({100*ru/total:.1f}%)")
    return 0


