// ─── Public API ──────────────────────────────────────────────────────────────
let _lang = "en";

function detectLanguage() {
  const candidates = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || "en"];
  for (const raw of candidates) {
    const short = String(raw).toLowerCase().split(/[-_]/)[0];
    if (I18N[short]) return short;
  }
  return "en";
}

function setLanguage(lang) {
  _lang = I18N[lang] ? lang : "en";
  document.documentElement.lang = _lang;
  document.documentElement.dir = RTL_LANGS.has(_lang) ? "rtl" : "ltr";
}

function getLanguage() { return _lang; }

function t(key, params) {
  const tab = I18N[_lang] || I18N.en;
  let str = (tab && tab[key]) || I18N.en[key];
  if (str === undefined) {
    // Missing string — return the key so the gap is obvious instead of
    // silently rendering nothing.
    return key;
  }
  if (params) {
    for (const k of Object.keys(params)) {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), String(params[k]));
    }
  }
  return str;
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });
}

// Run language detection ASAP so <html lang/dir> are correct before the
// rest of the JS executes.
setLanguage(detectLanguage());

